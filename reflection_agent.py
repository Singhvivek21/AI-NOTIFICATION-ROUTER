from schemas import HistoryEvidence, MediaAnalysis, MessageContext, RoutingDecision
import logging
from typing import Optional

from config import settings
from gemini_client import GeminiClient
from prompt_builder import PromptBuilder

# Configure module-level logger
logger = logging.getLogger(__name__)

# ==========================================
# REFLECTION AGENT SERVICE
# ==========================================

class ReflectionAgent:
    """
    Production-grade self-correction module.
    
    Acts as an autonomous peer-reviewer for the primary RouterAgent.
    It takes the initial RoutingDecision, cross-references it with the complete
    message context, historical evidence, and media analysis, and identifies
    inconsistencies, logical flaws, or miscalibrated confidence scores.
    
    If it detects an error, it generates a corrected RoutingDecision.
    If the original decision is sound, it returns it (potentially with increased confidence).
    """

    def __init__(self, gemini_client: GeminiClient, prompt_builder: PromptBuilder):
        self.client = gemini_client
        self.prompt_builder = prompt_builder

    async def review_decision(
        self,
        initial_decision: RoutingDecision,
        context: MessageContext,
        history: HistoryEvidence,
        media: Optional[MediaAnalysis] = None,
        use_pro_model: bool = True
    ) -> RoutingDecision:
        """
        Main entry point for the reflection workflow.
        
        Args:
            initial_decision: The RoutingDecision generated by the primary pass.
            context: The 360-degree structured context of the message.
            history: Historical engagement and message evidence.
            media: Multimodal analysis results (if applicable).
            use_pro_model: Whether to escalate to Gemini Pro for deeper reasoning.
            
        Returns:
            RoutingDecision: The reviewed and potentially corrected decision.
        """
        logger.info(f"Initiating reflection for message_id: {context.message_id}")
        
        model_target_str = "pro" if use_pro_model else "flash"
        model_name = settings.gemini_pro_model if use_pro_model else settings.gemini_flash_model

        try:
            # Build the reflection prompt package. 
            # (Note: prompt_builder handles injecting the initial decision for critique)
            prompt_pkg = self.prompt_builder.build_reflection_prompt(
                original_context=context,
                history=history,
                initial_decision=initial_decision.model_dump(),
                media=media,
                model_target=model_target_str
            )

            # Execute the LLM call enforcing the same strict RoutingDecision schema
            response = await self.client.generate_json(
                prompt=prompt_pkg.user_prompt,
                response_schema=RoutingDecision,
                system_instruction=prompt_pkg.system_prompt,
                model_name=model_name,
                temperature=0.2  # Slightly higher than primary routing to encourage critical evaluation
            )
            
            reviewed_decision: RoutingDecision = response.content
            
            # Log significant changes for observability
            self._log_correction_delta(context.message_id, initial_decision, reviewed_decision)
            
            return reviewed_decision

        except Exception as e:
            logger.error(
                f"Reflection agent encountered a critical error for message_id {context.message_id}. "
                f"Falling back to initial decision. Error: {e}"
            )
            # Failsafe: Never break the pipeline; fallback to the primary decision
            return initial_decision

    def _log_correction_delta(
        self, 
        message_id: str, 
        initial: RoutingDecision, 
        reviewed: RoutingDecision
    ) -> None:
        """
        Compares the initial and reviewed decisions to provide structured observability
        into the value added by the reflection step.
        """
        changes = []
        
        if initial.action != reviewed.action:
            changes.append(f"Action: {initial.action.value} -> {reviewed.action.value}")
            
        if initial.message_type != reviewed.message_type:
            changes.append(f"Type: {initial.message_type.value} -> {reviewed.message_type.value}")
            
        if abs(initial.confidence - reviewed.confidence) >= 0.1:
            changes.append(f"Conf: {initial.confidence} -> {reviewed.confidence}")

        if changes:
            logger.info(
                f"Reflection agent modified decision for {message_id} | Changes: " + " | ".join(changes)
            )
        else:
            logger.debug(f"Reflection agent agreed with initial decision for {message_id}")
